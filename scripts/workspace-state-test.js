const assert=require('assert')
const workspace=require('../utils/ai-workspace-state')
const initial=workspace.createState({entrySource:'home'})
const changed=workspace.switchPanel(initial,'qa')
assert.strictEqual(changed.activePanel,'qa')
assert.strictEqual(changed.entrySource,'home')
assert.strictEqual(changed.tripState.requestCount,0)
assert.strictEqual(changed.qaState.requestCount,0)
const invalid=workspace.switchPanel(changed,'not-a-panel')
assert.strictEqual(invalid.activePanel,'qa')
console.log('[WORKSPACE_STATE_TEST][PASS]',JSON.stringify({panels:workspace.PANELS,active:changed.activePanel,aiRequests:0}))
