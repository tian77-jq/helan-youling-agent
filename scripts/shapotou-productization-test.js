const assert=require('assert')
const adapter=require('../adapters/shapotou')
const {planExperience}=require('../core/experience-orchestrator')
const profile=adapter.getProfile()
assert.equal(profile.scenicId,'shapotou')
assert.equal(profile.rightsMode,'INDEPENDENT_POC')
assert(adapter.getExperienceCatalog().length>=3)
assert(adapter.getStoryCatalog().some(x=>x.evidenceLevel==='HIGH'))
assert(adapter.getMemoryTemplates().length>=1)
const oneDay=planExperience(adapter,{days:1,family:true,pace:'relaxed',includeNight:false})
assert.equal(oneDay.scenicId,'shapotou'); assert(oneDay.slots.length>=2); assert(!oneDay.slots.some(x=>x.slot==='night'))
const hotel=planExperience(adapter,{days:1,hotelGuest:true,stayOvernight:true})
assert(hotel.slots.some(x=>x.slot==='night'&&x.realtimeRequired))
console.log(`[SHAPOTOU_PRODUCTIZATION] PASS profile=1 experiences=${adapter.getExperienceCatalog().length} stories=${adapter.getStoryCatalog().length} memory=${adapter.getMemoryTemplates().length} core_change_for_mock_scenic=0`)
