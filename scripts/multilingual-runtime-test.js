const assert=require('assert')
const semantic=require('../utils/multilingual-semantic')
const tripAgent=require('../utils/trip-agent')
const {getLandmark,displayName}=require('../design-tokens/landmark-registry')

const arabic=semantic.canonicalizeQuestion('أريد زيارة منطقة شابوتو السياحية في نينغشيا لمدة يومين مع التاريخ والثقافة والطعام')
assert.ok(arabic.text.includes('沙坡头'),'Arabic POI aliases resolve to canonical Chinese names')
assert.ok(arabic.text.includes('历史'))
assert.ok(arabic.text.includes('文化'))
assert.ok(arabic.text.includes('美食'))
assert.ok(arabic.text.includes('宁夏'))
const english=semantic.canonicalizeQuestion('Plan a 2 day trip to the Western Xia Imperial Tombs and Yellow River in Ningxia')
assert.ok(english.text.includes('西夏陵'))
assert.ok(english.text.includes('黄河'))
assert.ok(english.text.includes('宁夏'))
assert.strictEqual(english.landmarkIds.includes('xixia-tombs'),true)
assert.strictEqual(getLandmark('shapotou').landmarkId,'shapotou','canonical identity does not change with translated display name')
assert.ok(displayName('shapotou','en-US').length>0)
assert.ok(displayName('shapotou','ar').includes('沙坡头'))
assert.strictEqual(tripAgent.normalizeLocale('ar'),'ar')
const plan=tripAgent.planTrip(arabic.text,{locale:'ar'})
assert.strictEqual(plan.locale,'ar')
assert.ok(/[\u0600-\u06ff]/.test(plan.summary),'Arabic fallback planner produces Arabic summary')
assert.ok(plan.days.length>0)
assert.ok(plan.days.every(day=>day.items.every(item=>item.time==='09:00'||/^\d{2}:\d{2}$/.test(item.time))))
const plannedIds=plan.days.flatMap(day=>day.items).filter(item=>item.type==='attraction').map(item=>item.knowledgeId)
assert.ok(plannedIds.every(id=>typeof id==='string'&&id.length>0),'plan keeps canonical knowledge IDs')
console.log(`MULTILINGUAL_RUNTIME_TEST PASS: Arabic/English aliases map to stable IDs; Arabic local planner=${plan.days.length} day(s); planned POIs=${plannedIds.length}`)
